const byId = new Map(manifest.packs.map((p) => [p.id, p]))
function upsert(entry) {
  const prev = byId.get(entry.id)
  if (prev) Object.assign(prev, entry)
  else {
    manifest.packs.push(entry)
    byId.set(entry.id, entry)
  }
}

